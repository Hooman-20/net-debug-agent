"""Step 4: the model writes a test script for this system; the user approves it; we run it with a timeout.

Usage:
  python tool_builder.py "measure speed from ns1 to ns2 with 1000 packets"
  python tool_builder.py --run tools/udp_speed_loss.py     # re-run a saved tool
  add --yes to skip the y/n approval (automated testing only)
"""
import os
import re
import subprocess
import sys
import time

from config import (LOCAL_IP, NAMESPACE, PEER_IP, PEER_NAMESPACE, RUN_AS_USER, SCRIPT_MAX_TOKENS,
                    SUMMARY_FILE, TOOL_PORT, TOOL_TIMEOUT, TOOLS_DIR)
from model import ask_model

SYSTEM_PROMPT = f"""You write small Python 3 network test scripts for a Linux system.

Lab layout:
- The script runs in network namespace {NAMESPACE} (IP {LOCAL_IP}).
- A peer namespace {PEER_NAMESPACE} has IP {PEER_IP}. They are directly connected.

Rules:
- Python 3 standard library only. You may call system tools listed as present in the system summary
  via subprocess with an argument list (never shell=True). Do not use tools listed as missing.
- The script runs as a normal user, not root. Do not change any system settings.
- The whole run must finish in under {TOOL_TIMEOUT - 5} seconds. Use timeouts on every socket and subprocess.
- Test the system as it is configured (its resolver, routes, interfaces). Do not hardcode a server
  or setting the user did not give, and never report PASS when the configured path fails.
- Print clear labeled results AND the raw evidence (e.g. the ping summary line, counts, timings).
- Exit with code 0 when the test ran, even if the network is bad. Only crash on real bugs.

Pick one TYPE. Speed and packet-loss tests are always two-sided; latency, MTU and DNS tests are
always one-sided.
- one-sided: the test only needs {NAMESPACE} (latency, MTU, DNS, ...). Runs with no arguments.
- two-sided: the test needs a program on both ends (UDP speed, UDP packet loss, ...). The script takes
  --role sender|receiver. The receiver runs in {PEER_NAMESPACE}, binds {PEER_IP}:{TOOL_PORT}, and is
  started 1 second before the sender. The receiver must exit by itself (e.g. 3 seconds after the last
  packet, or 10 seconds if nothing arrives) and print the final results (packets received, loss %,
  throughput). Put sequence numbers and the total count in each packet so loss can be computed even
  if the last packets are lost. Pace the sender (about 1 ms between packets) so receiver buffer
  overflow is not mistaken for network loss. The sender runs in {NAMESPACE} and prints what it sent.

Reply in exactly this format:
TYPE: one-sided or two-sided
NAME: short_snake_case_name
```python
<the full script>
```"""


def load_summary():
    if not os.path.exists(SUMMARY_FILE):
        sys.exit("No system summary yet. Run: python discover.py")
    with open(SUMMARY_FILE) as f:
        return f.read()


def parse_tool(reply):
    """Return (tool_type, name, code) or raise ValueError."""
    t = re.search(r"TYPE:\s*(one-sided|two-sided)", reply, re.I)
    n = re.search(r"NAME:\s*([A-Za-z0-9_\-]+)", reply)
    c = re.search(r"```(?:python)?\s*\n(.*?)```", reply, re.S)
    if not (t and c):
        raise ValueError("model reply missing TYPE or code block")
    name = re.sub(r"[^a-z0-9_]", "_", (n.group(1) if n else "tool").lower())[:40].strip("_") or "tool"
    return t.group(1).lower(), name, c.group(1).rstrip() + "\n"


def save_tool(name, tool_type, request, code):
    """Save under tools/<name>.py (or <name>_2.py, ...). Returns the path."""
    os.makedirs(TOOLS_DIR, exist_ok=True)
    path, i = os.path.join(TOOLS_DIR, f"{name}.py"), 2
    while os.path.exists(path):
        path, i = os.path.join(TOOLS_DIR, f"{name}_{i}.py"), i + 1
    header = (f"# Generated by the network debugging agent\n"
              f"# Request: {' '.join(request.split())}\n"
              f"# TYPE: {tool_type}\n"
              f"# Re-run: python tool_builder.py --run tools/{os.path.basename(path)}\n")
    with open(path, "w") as f:
        f.write(header + code)
    return path


def read_tool(path):
    """Load a saved tool. Returns (tool_type, request, code)."""
    with open(path) as f:
        code = f.read()
    t = re.search(r"^# TYPE: (one-sided|two-sided)", code, re.M)
    r = re.search(r"^# Request: (.*)$", code, re.M)
    return (t.group(1) if t else "one-sided"), (r.group(1) if r else ""), code


def ns_cmd(ns, path, args=()):
    """Run the script in a namespace, as a normal user, hard-killed after TOOL_TIMEOUT seconds."""
    return ["sudo", "-n", "ip", "netns", "exec", ns, "timeout", "-s", "KILL", str(TOOL_TIMEOUT),
            "runuser", "-u", RUN_AS_USER, "--", "python3", "-I", path, *args]


def plan_text(tool_type):
    if tool_type == "two-sided":
        return (f"  1. receiver: {PEER_NAMESPACE} ({PEER_IP})   python3 <script> --role receiver\n"
                f"  2. sender:   {NAMESPACE} ({LOCAL_IP})   python3 <script> --role sender  (1 s later)")
    return f"  {NAMESPACE} ({LOCAL_IP})   python3 <script>"


def approve(path, tool_type, code, auto_approve=False):
    """Show the script and ask y/n. auto_approve=True is for automated testing only."""
    print(f"\n{'=' * 70}\n{path}  [{tool_type}]\n{'=' * 70}")
    print(code)
    print("=" * 70)
    print(f"Will run as user '{RUN_AS_USER}', killed after {TOOL_TIMEOUT}s:\n{plan_text(tool_type)}")
    if auto_approve:
        print("run? (y/n) y  [auto-approved]")
        return True
    try:
        return input("run? (y/n) ").strip().lower() == "y"
    except EOFError:  # no terminal: never run without an explicit yes
        return False


def _describe(label, rc, out, err):
    status = "killed: timed out" if rc in (137, -9) else f"exit code {rc}"
    text = f"=== {label} ({status}) ===\n{out}"
    if err.strip():
        text += f"\n[stderr]\n{err}"
    return text


def run_tool(path, tool_type):
    """Run the tool. Returns (ok, combined_output)."""
    if tool_type == "one-sided":
        try:
            p = subprocess.run(ns_cmd(NAMESPACE, path), capture_output=True, text=True,
                               timeout=TOOL_TIMEOUT + 5)
            rc, out, err = p.returncode, p.stdout, p.stderr
        except subprocess.TimeoutExpired:
            rc, out, err = 137, "", ""
        return rc == 0, _describe(f"{NAMESPACE}", rc, out, err)

    recv = subprocess.Popen(ns_cmd(PEER_NAMESPACE, path, ["--role", "receiver"]),
                            stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True)
    time.sleep(1)
    try:
        s = subprocess.run(ns_cmd(NAMESPACE, path, ["--role", "sender"]), capture_output=True,
                           text=True, timeout=TOOL_TIMEOUT + 5)
        s_rc, s_out, s_err = s.returncode, s.stdout, s.stderr
    except subprocess.TimeoutExpired:
        s_rc, s_out, s_err = 137, "", ""
    try:
        r_out, r_err = recv.communicate(timeout=TOOL_TIMEOUT + 5)
        r_rc = recv.returncode
    except subprocess.TimeoutExpired:
        recv.kill()
        r_out, r_err = recv.communicate()
        r_rc = 137
    output = (_describe(f"sender in {NAMESPACE}", s_rc, s_out, s_err) + "\n"
              + _describe(f"receiver in {PEER_NAMESPACE}", r_rc, r_out, r_err))
    return s_rc == 0 and r_rc == 0, output


def ask_for_tool(request, summary):
    messages = [
        {"role": "system", "content": SYSTEM_PROMPT},
        {"role": "user", "content": f"System summary:\n{summary}\n\nRequest: {request}"},
    ]
    reply = ask_model(messages, max_tokens=SCRIPT_MAX_TOKENS)
    return messages + [{"role": "assistant", "content": reply}], reply


def ask_for_fix(messages, output):
    messages = messages + [{"role": "user", "content":
        f"The script failed. Output and error:\n{output[-3000:]}\n\n"
        "Fix it. Reply in the same format (TYPE, NAME, code block) with the full fixed script."}]
    return ask_model(messages, max_tokens=SCRIPT_MAX_TOKENS)


def approve_and_run(path, tool_type, code, auto_approve=False):
    """Returns (ran, ok, output). ran=False if the user said no."""
    if not approve(path, tool_type, code, auto_approve):
        print("Not run.")
        return False, False, ""
    print("Running...")
    ok, output = run_tool(path, tool_type)
    print(output)
    return True, ok, output


def run_with_one_fix(path, tool_type, code, messages, request, auto_approve=False):
    """Approve and run; on failure, ask the model for one fix and approve/run that.
    Returns (path, output) of the last run, or (path, None) if the user declined."""
    ran, ok, output = approve_and_run(path, tool_type, code, auto_approve)
    if not ran or ok:
        return path, output if ran else None

    print("\nThe script failed. Sending the error back to the model for one fix attempt...")
    try:
        tool_type, _, fixed = parse_tool(ask_for_fix(messages, output))
    except ValueError as e:
        print(f"Could not get a fixed script: {e}")
        return path, output
    name = os.path.splitext(os.path.basename(path))[0]
    path = save_tool(f"{name}_fixed", tool_type, request, fixed)
    _, _, fixed = read_tool(path)
    ran, ok, output = approve_and_run(path, tool_type, fixed, auto_approve)
    if ran and not ok:
        print("\nThe fixed script failed too. Giving up on this request.")
    return path, output if ran else None


def build_and_run(request, summary=None, auto_approve=False):
    """Full step 4 flow: model writes a tool, user approves, we run it (with one fix attempt)."""
    summary = summary or load_summary()
    print(f"Asking the model for a tool: {request!r}")
    messages, reply = ask_for_tool(request, summary)
    tool_type, name, code = parse_tool(reply)
    path = save_tool(name, tool_type, request, code)
    _, _, code = read_tool(path)
    return run_with_one_fix(path, tool_type, code, messages, request, auto_approve)


def rerun(path, auto_approve=False):
    """Re-run a saved tool (for the demo). A crash still gets one fix attempt."""
    path = os.path.abspath(path)
    tool_type, request, code = read_tool(path)
    messages = [
        {"role": "system", "content": SYSTEM_PROMPT},
        {"role": "user", "content": f"System summary:\n{load_summary()}\n\nRequest: {request}"},
        {"role": "assistant", "content": f"TYPE: {tool_type}\nNAME: tool\n```python\n{code}```"},
    ]
    return run_with_one_fix(path, tool_type, code, messages, request, auto_approve)


if __name__ == "__main__":
    args = sys.argv[1:]
    yes = "--yes" in args
    args = [a for a in args if a != "--yes"]
    if len(args) == 2 and args[0] == "--run":
        rerun(args[1], auto_approve=yes)
    else:
        req = " ".join(args) or input("What should I measure? ")
        build_and_run(req, auto_approve=yes)
